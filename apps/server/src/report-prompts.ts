/**
 * 硬规则（违反即视为缺陷）
 *
 * 两条口径**共用第 1–9 条的原文**（变更表 #137：共用规则一条都不许弱化）；
 * 只有第 3 条（不给决策建议）与第 9 条（每章字数预算）按口径收紧/换数，
 * 第 10 条（客户没给的数字不许编）是建设方案独有。
 */
function hardRules(kind: ReportKind): string {
  const construction = kind === "construction";
  const noAdvice = construction
    ? `3. **不给决策建议**：不写"建议先做试点""推荐采用""值得投入""应当优先"——产品只给事实、判定与缺口，
   进不进、什么时候进由用户决定。**建设工作方案另加**：「建议采用」「推荐」「值得投入」同样不许出现——
   方案是"已经定了怎么建"的陈述，不是选项比较，要推动的事写成安排（"由技术信息部在第 2—3 个月完成"）。`
    : `3. **不给决策建议**：不写"建议先做试点""推荐采用""值得投入""应当优先"——产品只给事实、判定与缺口，
   进不进、什么时候进由用户决定。`;
  const budget = construction
    ? `9. **每章有字数预算**（表格里的字不算）：背景约 400–700、目标约 400–800、内容约 2000–2900
   （这是天然的大章，不要为了均摊篇幅把它压扁）、路径约 400–800、安排 0（靠表说话）、保障约 400–600、展望约 150–250；
   写超了就是没归纳——把并列的事实合并成一条结论，把细节留给表格。`
    : `9. **每章有字数预算**（表格里的字不算）：现状约 900、方案约 1200、场景与问题 200–300、下一步 300–400、价值以表格为主；
   写超了就是没归纳——把并列的事实合并成一条结论，把细节留给表格。`;
  const extra = construction
    ? `

10. **客户没给的数字不许编**：金额、台数、数量、比例，材料里没有就写「待客户提供」「待现场勘查确定」，
    并把口径写在数字旁边（例如「设备台数待现场勘查按班组数确定」「费率待客户提供预算口径」）；
    **禁止编造具体金额或台数**，也不许用"约 X 万元""预计 Y 台"包装一个自己算的数。
    素材里已有的金额与台数照抄不改（预计 181 万元 / 合计约 481 万元 / 6 台（1 台/公司））。`
    : "";

  return `## 硬规则（违反即视为缺陷）

1. **这是方案，不是前面内容的总结**：读者没看过我们内部的调研表，他读到的应该是**一份能独立成立的方案**。
   素材只是证据——你要基于它给出**我们自己的主张**：设计原则、总体架构、职责怎么分、接口在哪、
   每项价值对应哪个指标、我们明确不做什么、下一步做什么。
   **禁止**逐行搬运表格、**禁止**把每一行写成一条 bullet、**禁止**出现"表X-X"这类内部表号，
   **禁止**写成"先讲了位 … 又说了 …"这种摘要腔。
2. **每条结论必须立得住**：数据里标了「行业通例（模型知识）」「单一来源」的，结论里必须**降调**
   （写"行业通行做法如此，本客户是否同样如此待验证"），**不许当成本客户事实**。
${noAdvice}
4. **写不出来的就说缺**：数据里没有的（本客户基线、现场设备清单、合同条款等）写成「待补」并说明缺什么；
   宁可短，不许编。
5. **说人话**：术语首次出现要有解释；一句话说清一件事，不堆形容词，不用"赋能/抓手/闭环"这类空话。
5.1 **正文里不许再用「一、二、三、」编号**：章号由 Word 文档自动编号，正文里再用就和章节层级混在一起
   （实测：价值条目写成「**二、按预约自动就绪…**」这种，读者以为又开了一章）。分条改用「价值一 / 原则二 / 第一 / 其一 / （2）」这类写法。
6. **数字要带口径**：出现数字必须写清是"行业通例量级"还是"本客户实测"，以及量的是什么。
7. **不许写自我说明与免责声明**：「本材料只陈述信息与安排」「数值为按材料口径的测算，以试点实测为准」
   「除特别说明外」「本节出现的数字均来自行业判断」「不含决策建议」这类澄清、口径、免责的话**一律不写**——
   要交代的口径直接写在数字旁边（例如「（行业通例量级）」），别单起一句说自己在怎么写。
8. **不许记流水账**：同一个事实全篇只出现一次（别在各章反复铺垫）；正文给**结论 + 最少必要依据**，
   结构交给表格（架构 / 职责 / 选型 / 步骤），不要一条条罗列素材里的行；一段写不出「所以呢」就删掉。
${budget}${extra}`;
}


/** 输出格式：章节与小节由契约按口径给出，标题只写章名（序号交给 Word 自动编号） */
function outputFormat(kind: ReportKind): string {
  const layout = CHAPTER_LAYOUT[kind];
  const chapters = reportChapters(kind);
  const firstHeading = reportChapterHeading(kind, chapters[0]?.key ?? "");
  const lines = chapters.flatMap((c) => [
    `- \`## ${reportChapterHeading(kind, c.key)}\``,
    ...c.sections.map(renderSection),
    ...(layout[c.key] ? [`  - ${layout[c.key]}`] : []),
  ]);
  return [
    "## 输出格式（严格遵守）",
    "",
    "纯 Markdown，**不要**任何前言、寒暄、结语或代码块围栏。按下面的章节与小节写，标题**原样使用**：",
    ...lines,
    "",
    "层级只到 `###`（不要 `#`、`####` 及更深）；正文里不写文件名、页码、内部表号。",
    "**章节号由 Word 文档自动编号（1 / 1.1 / 1.1.1），正文与标题都不要自己写序号。**",
    `**章名只写一次**：\`## ${firstHeading}\` 之后不要再把「${firstHeading}」当正文第一行抄一遍。`,
  ].join("\n");
}


/** 一节要写什么：小节名 + 该自建的构件 */
function renderSection(sec: ReportSection): string {
  const arts = sec.artifacts ?? [];
  const what = arts.length === 0 ? "文字叙述" : `必须${arts.map((a) => ARTIFACT_HINT[a]).join("；并且")}`;
  // 有些内容用户定稿是"章下直接写"的（场景边界 / 典型问题 / 价值表 / 建设方案的背景与计划表），不要套小节标题
  if (sec.noHeading) return `  - 「${sec.title}」：**章下直接写，不要单独加 \`###\` 标题**——${what}`;
  return `  - \`### ${sec.title}\`：${what}`;
}


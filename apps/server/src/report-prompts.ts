/**
 * 补写提示词：只写缺的那几章
 *
 * 整篇写容易漏章（模型常把第一章当上下文），补写时把范围缩到"就写这几节"，
 * 命中率明显更高；原料同样给全量。变更表 #137：标题句带口径名与章序号。
 */
export function buildChapterPrompt(
  kind: ReportKind,
  chapters: readonly ChapterDigest[],
  scenarioName: string,
): { system: string; user: string } {
  const label = `${scenarioName}${REPORT_KIND_LABEL[kind]}`;
  const all = reportChapters(kind);
  const user = [
    `## 场景`,
    scenarioName,
    "",
    "## 只写下面这几节（其余章节已经写好，不要重复、不要写别的章节）",
    chapters
      .map((c) => {
        const index = all.findIndex((x) => x.key === c.key);
        const ordinal = index >= 0 ? `第 ${index + 1} 章` : "本节";
        return [
          `写《${label}》的${ordinal}「${c.title}」：`,
          `### ${c.title}`,
          reportSectionsOf(kind, c.key).map(renderSection).join("\n"),
          "",
          c.markdown,
        ]
          .filter((x) => x !== "")
          .join("\n");
      })
      .join("\n\n"),
    "",
    "## 输出格式（必须严格遵守）",
    ...chapters.map((c) => `- 以「## ${c.title}」开头，本节内容完整写出`),
    "",
    "每节先用一段话给出这一节的结论，再给必要的支撑；同类信息合并，不要逐行罗列。",
    "不要写开场白、不要写目录、不要用代码块包裹。",
  ].join("\n");
  return { system: buildSystem(kind), user };
}

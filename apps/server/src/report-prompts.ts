/** 场景锚：让模型先把边界读准 */
function renderAnchor(anchor: readonly Record<string, unknown>[]): string {
  if (anchor.length === 0) return "（尚未产出场景锚表1-1）";
  return anchor
    .map((r) => `- ${String(r["item"] ?? "")}：${String(r["content"] ?? "").replace(/\s+/g, " ")}`)
    .join("\n");
}


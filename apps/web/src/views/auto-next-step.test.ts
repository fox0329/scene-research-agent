import { describe, expect, it } from "vitest";
import type { ApiFlowStatus, ApiFlowStep } from "../api";
import { shouldAutoGenerateDelivery, shouldAutoGenerateStep } from "./auto-next-step";

function step(patch: Partial<ApiFlowStep>): ApiFlowStep {
  return {
    id: 2,
    key: "stage1",
    title: "认识场景",
    short: "认识场景",
    goal: "",
    kind: "分析",
    state: "当前",
    ready: false,
    readyHint: "",
    progress: { tablesWithData: 0, expectedTables: 1, rows: 0 },
    ...patch,
  };
}

function flow(steps: ApiFlowStep[], currentStep = 2): ApiFlowStatus {
  return { steps, currentStep, completedCount: 1, finished: false };
}

describe("shouldAutoGenerateStep", () => {
  it("分析步未产出、未在跑：自动生成", () => {
    expect(shouldAutoGenerateStep(flow([step({})]), 2)).toBe(true);
  });

  it("分析步已有内容：不覆盖，交给用户先看", () => {
    expect(shouldAutoGenerateStep(flow([step({ ready: true })]), 2)).toBe(false);
  });

  it("分析步服务端已在跑：不重复发起", () => {
    expect(shouldAutoGenerateStep(flow([step({ running: true })]), 2)).toBe(false);
  });

  it("确认步/组装步走各自入口，不自动跑分析", () => {
    expect(shouldAutoGenerateStep(flow([step({ id: 1, kind: "确认" })]), 1)).toBe(false);
    expect(shouldAutoGenerateStep(flow([step({ id: 6, kind: "组装" })]), 6)).toBe(false);
  });

  it("目标步不存在：不动作", () => {
    expect(shouldAutoGenerateStep(flow([step({})]), 99)).toBe(false);
  });
});

describe("shouldAutoGenerateDelivery", () => {
  it("进入未产出的组装步：自动写报告", () => {
    expect(shouldAutoGenerateDelivery(flow([step({ id: 6, kind: "组装" })]), 6)).toBe(true);
  });

  it("已有报告或服务端在跑：不抢跑", () => {
    expect(
      shouldAutoGenerateDelivery(flow([step({ id: 6, kind: "组装", ready: true })]), 6),
    ).toBe(false);
    expect(
      shouldAutoGenerateDelivery(flow([step({ id: 6, kind: "组装", running: true })]), 6),
    ).toBe(false);
  });
});

/**
 * 资料上传口径（contract v1.x）
 *
 * 为什么这个数字要放在契约里：服务端 multipart 上限与前端上传前的预检**必须是同一个数**，
 * 否则会出现"前端放行、服务端 413"这种只有用户才会发现的错位（变更表 #155 的真实现象：
 * 165 MB 的 PPT 上传被旧上限挡掉，界面只回一句英文 `request file too large`）。
 *
 * 口径变更（变更表 #156，用户 2026-10-09 定调）：**50 MB → 300 MB**。
 * 原来的 50 MB 是早期"白皮书上限"——那时假定输入是一份几十页的白皮书；现在真实输入是
 * 解决方案 PPT / 整本技术资料（用户手上就有一份 165 MB 的 PPT），按 50 MB 拦等于让用户
 * 先手工拆文件。提到 300 MB 的同时，服务端改成**流式落盘**（不再 `toBuffer()` 整读进内存），
 * 否则这个上限会直接把进程内存顶爆（变更表 #156 任务 1）。
 */
export const FILE_UPLOAD_LIMIT_MB = 300;
